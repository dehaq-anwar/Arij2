export const fill = (text: string, values: Record<string, string | number>) =>
  text.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ''))

/** Dates and times in the admin language (Arabic with Latin digits, like the website). */
/** The association's time zone: server-rendered times must not follow the server's (UTC). */
export const TIME_ZONE = 'Europe/Berlin'

/** Greeting by the hour in the association's time zone. */
export function greeting(t: Texts, now = new Date()) {
  // formatToParts: the formatted string itself is "13 Uhr" in German, not a number.
  const hour = Number(
    new Intl.DateTimeFormat('en-GB', { hour: 'numeric', hourCycle: 'h23', timeZone: TIME_ZONE })
      .formatToParts(now)
      .find((part) => part.type === 'hour')?.value,
  )
  return hour < 11 ? t.greetingMorning : hour < 18 ? t.greetingDay : t.greetingEvening
}

export const formatDateTime = (
  value: string | Date | null | undefined,
  language: AdminLanguage,
) => {
  if (!value) return '—'
  const locale = language === 'ar' ? 'ar-u-nu-latn' : language === 'en' ? 'en-GB' : 'de-DE'
  return new Intl.DateTimeFormat(locale, {
    dateStyle: 'medium',
    timeStyle: 'short',
    timeZone: TIME_ZONE,
  }).format(new Date(value))
}

export const formatDate = (value: string | Date | null | undefined, language: AdminLanguage) => {
  if (!value) return '—'
  const locale = language === 'ar' ? 'ar-u-nu-latn' : language === 'en' ? 'en-GB' : 'de-DE'
  return new Intl.DateTimeFormat(locale, { dateStyle: 'medium', timeZone: TIME_ZONE }).format(
    new Date(value),
  )
}
